# Position refresh must refetch the live year, preserve history and feed the app.
original <- getwd(); root <- tempfile('positions-test-'); dir.create(root)
dir.create(file.path(root,'raw','bref_position_estimates_by_year'),recursive=TRUE)
env <- new.env(parent=globalenv())
sys.source(file.path(original,'script/data/pull_bref_position_estimates.R'),env)
old <- data.frame(year=2026,player_name='Historical Player',pg_share=1,sg_share=0,sf_share=0,pf_share=0,c_share=0)
write.csv(old,file.path(root,'raw/bref_position_estimates.csv'),row.names=FALSE)
env$fetch_year <- function(year) data.frame(year=year,player_name=paste('Player',1:100),pg_share=0,sg_share=.2,sf_share=.8,pf_share=0,c_share=0)
previous <- Sys.getenv(c('BREF_POSITION_YEARS','BREF_POSITION_REFRESH'),unset=NA_character_)
Sys.setenv(BREF_POSITION_YEARS='2027',BREF_POSITION_REFRESH='true')
out <- env$run_position_refresh(root)
combined <- read.csv(file.path(root,'raw/bref_position_estimates.csv'))
stopifnot(nrow(combined)==101,sum(combined$year==2026)==1,out$seasons[['2027']]$status=='fresh')
env$fetch_year <- function(year) stop('Source unavailable')
out <- env$run_position_refresh(root)
stopifnot(out$seasons[['2027']]$status=='cached',nrow(read.csv(file.path(root,'raw/bref_position_estimates.csv')))==101)
for (k in names(previous)) if(is.na(previous[[k]])) Sys.unsetenv(k) else do.call(Sys.setenv,setNames(list(previous[[k]]),k))
sys.source(file.path(original,'script/frontend/player_pool.R'),env)
record <- list(app_nba_id=-7,nba_id=777,position='SG',source='espn_roster',pg_share=0,sg_share=1,sf_share=0,pf_share=0,c_share=0)
jsonlite::write_json(list(season=2027,generated_at='now',players=list(record)),file.path(root,'raw/live/positions.json'),auto_unbox=TRUE)
rows <- data.frame(nba_id=-7,year=2027,position='UNK',pg_share=0,sg_share=0,sf_share=0,pf_share=0,c_share=0,position_index=NA_real_,position_entropy=NA_real_)
out <- env$apply_live_positions(rows,root)
stopifnot(out$position=='SG',out$sg_share==1,out$position_index==2,out$position_source=='espn_roster')
unlink(root,recursive=TRUE)
cat('Daily position refresh, history preservation, cache fallback and app application passed\n')
